"""Відбитки того, що саме породило факт чи сигнал (EU AI Act ст. 12).

Провенанс без версії відповідає на питання «звідки взято», але не на питання
«чим саме». Через півроку це різниця між «цей креатинін витягла модель X з
промптом Y за правилами v3» і «щось його витягло».

Два види відбитка, бо два види зміни поведінки:

- **промпт** — для генеративного шляху. Зміна промпту зсуває витяг так само, як
  зміна ваг, тож вона мусить бути видна в аудиті;
- **набір правил** — для детермінованого. Зміна референсної межі перетворює
  спокійний показник на сигнал, не змінивши жодного рядка коду.

Хеш короткий (8 hex) — його читає людина в журналі, а не система безпеки; від
підбору тут нічого не залежить.
"""
from __future__ import annotations

import hashlib

__all__ = ["fingerprint", "agent"]


def fingerprint(text: str) -> str:
    """Стабільний короткий відбиток тексту (промпту, набору правил)."""
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:8]


def agent(name: str, model: str | None = None) -> str:
    """Ідентифікатор агента витягу: ``name@model`` або просто ``name``.

    Модель береться з фактичної конфігурації виклику, а не з літерала в коді:
    саме тому старий дефолт ``"MedGemma-4B"`` був гіршим за відсутність поля.
    """
    return f"{name}@{model}" if model else name

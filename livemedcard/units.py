"""Нормалізація одиниць виміру — запобіжник перед детермінованими сигналами L2a.

Значення без узгодженої одиниці порівнювати з референсною межею НЕ можна: глюкоза
100 mg/dL проти меж 3.9–6.1 mmol/L дасть хибне «вище норми». Тому L2a спершу питає
`same_unit`, і якщо одиниці не збігаються (або одиниці факту немає) — сигнал не
формується, а натомість піднімається `unit_mismatch` (мовчазний пропуск гірший за
явну незгоду).

Свідомо БЕЗ конверсій: перерахунок mg/dL → mmol/L потребує коефіцієнта на кожен
аналіт, і помилка в ньому — це хибний клінічний сигнал. Канонічний UCUM-шар із
таблицею конверсій — у роадмапі; тут лише чесне «одиниці не збігаються».
"""
from __future__ import annotations

import re
from typing import Optional

# Написання однієї й тієї ж одиниці різняться за джерелом (UA-бланк, EN-бланк,
# OCR-модель): зводимо до спільного ключа.
_ALIASES: dict[str, str] = {
    "umol/l": "umol/l", "мкмоль/л": "umol/l",
    "mmol/l": "mmol/l", "ммоль/л": "mmol/l",
    "mg/dl": "mg/dl", "мг/дл": "mg/dl",
    "g/l": "g/l", "г/л": "g/l",
    "mmhg": "mmhg", "мм рт.ст.": "mmhg", "мм рт. ст.": "mmhg",
    "%": "%",
}


# Написання, які реально трапляються в документах — саме їх читає екстрактор
# після числа. Список ЗАКРИТИЙ навмисно: загальний шаблон «слово після числа»
# ковтав би «натще», «ммоль» без знаменника і решту тексту, а вигадана одиниця
# гірша за відсутню — вона проходить перевірку `same_unit` і тихо вмикає
# порівняння з межами.
_SPELLINGS = (
    "µmol/L", "μmol/L", "umol/L", "мкмоль/л",
    "mmol/L", "ммоль/л",
    "mg/dL", "мг/дл",
    "g/L", "г/л",
    "mmHg", "мм рт.ст.", "мм рт. ст.",
    "%",
)
UNIT_PATTERN = "|".join(
    re.escape(u) for u in sorted(_SPELLINGS, key=len, reverse=True)
)


def canonical(unit: Optional[str]) -> Optional[str]:
    """Одиниця у канонічному вигляді; None — коли одиниці немає."""
    if not unit:
        return None
    u = unit.strip().lower()
    # µ (micro sign) і μ (грецька мю) — різні кодпойнти, обидва означають «мікро».
    u = u.replace("µ", "u").replace("μ", "u")
    u = " ".join(u.split())
    return _ALIASES.get(u, u)


def same_unit(a: Optional[str], b: Optional[str]) -> bool:
    """Чи можна порівнювати два значення напряму.

    Відсутня одиниця — НЕ привід вважати збіг: невідоме не дорівнює очікуваному.
    """
    ca, cb = canonical(a), canonical(b)
    if ca is None or cb is None:
        return False
    return ca == cb
